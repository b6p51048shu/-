/** slug から品目を取得 */
export function getItemBySlug(slug: string): GomiItem | undefined {
  return GOMI_ITEMS.find((i) => i.slug === slug);
}

/** カテゴリ別にグループ化（インデックスページ用） */
export function groupItemsByCategory(): { category: ItemCategory; items: GomiItem[] }[] {
  const order: ItemCategory[] = ["burnable", "unburnable", "recyclable", "sodai", "kaden", "kogata", "hazard"];
  return order
    .map((category) => ({ category, items: GOMI_ITEMS.filter((i) => i.category === category) }))
    .filter((g) => g.items.length > 0);
}
